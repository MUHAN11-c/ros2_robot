def patch(path, pairs):
    p = ROOT / path
    text = p.read_text(encoding="utf-8")
    hit = False
    for old, new in pairs:
        got = text.count(old)
        if got == 0 and new in text:
            continue  # 已应用
        assert got == 1, f"{path}: 「{old[:36]}…」实际 {got} 处"
        text = text.replace(old, new)
        hit = True
    if hit:
        p.write_text(text, encoding="utf-8")
        CHANGED.append(path)


